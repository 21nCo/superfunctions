// Emits the TypeScript package files.

import type { CatalogOperation } from "@apifn/contracts";
import type { SdkDiagnostic, SdkFile, SdkTargetContext, SdkTargetOutput } from "../../types.js";
import { camelCase, docComment, NameRegistry, pascalCase, propertyKey } from "./naming.js";
import { analyzeOperation, isReadMethod, type ResponseShape } from "./operations.js";
import type { TypeScriptOptions } from "./options.js";
import { RUNTIME_SOURCE } from "./runtime-source.js";
import { SchemaTypes } from "./schema.js";

export const CUSTOM_CODE_ROOT = "src/custom/";
/** TypeScript used to build generated packages; pinned so builds are reproducible. */
export const TYPESCRIPT_VERSION = "5.9.3";

/** Names exported by runtime.ts through index.ts. */
const RUNTIME_EXPORTS = [
  "ApiAbortError",
  "ApiError",
  "ApiFailureKind",
  "ApiHttpError",
  "ApiTimeoutError",
  "BasicCredential",
  "ClientFailureObservation",
  "ClientOptions",
  "CredentialSource",
  "RequestOptions",
  "RetryOptions",
];

function header(context: SdkTargetContext<TypeScriptOptions>): string {
  return `// Generated by ${context.generator.name} ${context.generator.version} (target ${context.target.id} ${context.target.version}). Do not edit: regeneration replaces this file.\n`;
}

function responseType(shape: ResponseShape, types: SchemaTypes): string {
  const members = shape.contents.map(({ kind, schema }) =>
    kind === "json" ? types.type(schema) : kind === "text" ? "string" : kind === "binary" ? "Uint8Array" : "undefined"
  );
  return [...new Set(members)].join(" | ") || "unknown";
}

export function emitTypeScript(context: SdkTargetContext<TypeScriptOptions>): SdkTargetOutput {
  const { catalog, options } = context;
  const diagnostics: SdkDiagnostic[] = [];
  const names = new NameRegistry();
  const claim = (name: string, owner: string, pointer?: string, operation?: string) => {
    const previous = names.claim(name, owner);
    if (previous !== null) {
      diagnostics.push({
        code: "SDK_NAME_COLLISION",
        severity: "error",
        message: `Exported name "${name}" is generated for both ${previous} and ${owner}; rename one (options.typeNames for component schemas, the manifest's name for operations).`,
        pointer,
        operation,
      });
    }
  };
  for (const name of RUNTIME_EXPORTS) claim(name, `the runtime export ${name}`);
  claim(options.clientName, "the client class", "/options/clientName");
  claim(`${options.clientName}Credentials`, "the client credentials type", "/options/clientName");
  claim(`${options.clientName}Options`, "the client options type", "/options/clientName");
  claim("OperationErrors", "the operation error map");
  claim("isOperationError", "the operation error guard");

  // Models: every component schema the catalog publishes, sorted by name.
  const schemaNames = Object.keys(catalog.schemas).sort();
  const typeNames = new Map<string, string>();
  for (const schema of schemaNames) {
    const typeName = Object.prototype.hasOwnProperty.call(options.typeNames, schema) ? options.typeNames[schema] : pascalCase(schema);
    typeNames.set(schema, typeName);
    claim(typeName, `component schema "${schema}"`, `/schemas/${schema.replace(/~/g, "~0").replace(/\//g, "~1")}`);
  }
  const resolve = (component: string) => typeNames.get(component) ?? null;
  const modelTypes = new SchemaTypes(resolve);
  const clientTypes = new SchemaTypes(resolve, "Models.");
  let models = header(context);
  for (const schema of schemaNames) {
    const value = catalog.schemas[schema];
    const description = typeof value === "object" && value !== null && !Array.isArray(value) && typeof value.description === "string" ? value.description : null;
    models += `\n${docComment([description])}export type ${typeNames.get(schema)} = ${modelTypes.type(value)};\n`;
  }
  if (schemaNames.length === 0) models += "\nexport {};\n";

  // Operations.
  const schemes = new Map<string, string>();
  const specs: string[] = [];
  const declarations: string[] = [];
  const methods: string[] = [];
  const errorEntries: string[] = [];
  const unsupportedSchemes = new Set<string>();
  for (const operation of context.operations) {
    const shape = analyzeOperation(operation, catalog);
    const pointer = `/operations/${catalog.operations.indexOf(operation)}`;
    shape.unsupportedSchemes.forEach((scheme) => unsupportedSchemes.add(scheme));
    if (operation.servers !== null) {
      diagnostics.push({
        code: "SDK_SERVERS_IGNORED",
        severity: "warning",
        message: `${operation.id} declares its own servers; the client sends it to the configured base URL like every other operation.`,
        pointer: `${pointer}/servers`,
        operation: operation.id,
      });
    }
    const prefix = pascalCase(operation.name);
    const owner = `operation ${operation.id}`;
    // A method named constructor would replace the client's constructor.
    if (operation.name === "constructor") {
      diagnostics.push({ code: "SDK_NAME_COLLISION", severity: "error", message: `${operation.id}: method name "constructor" collides with the client constructor; set another name in the manifest.`, pointer: `${pointer}/name`, operation: operation.id });
    }
    for (const suffix of ["Params", "Result", "Error"]) claim(`${prefix}${suffix}`, owner, `${pointer}/name`, operation.id);

    // Parameters become camelCase keys of one params object, next to `body`.
    const keys = new Map<string, string>();
    const paramSpecs: string[] = [];
    const paramFields: string[] = [];
    for (const [position, parameter] of operation.parameters.entries()) {
      const key = camelCase(parameter.name);
      const previous = keys.get(key) ?? (key === "body" && shape.body ? "the request body" : undefined);
      if (previous !== undefined) {
        diagnostics.push({
          code: "SDK_NAME_COLLISION",
          severity: "error",
          message: `${operation.id}: ${parameter.in} parameter "${parameter.name}" and ${previous} both become the params key "${key}".`,
          pointer: `${pointer}/parameters/${position}`,
          operation: operation.id,
        });
      }
      keys.set(key, `${parameter.in} parameter "${parameter.name}"`);
      const required = parameter.in === "path" || parameter.required;
      paramSpecs.push(
        `{ key: ${JSON.stringify(key)}, name: ${JSON.stringify(parameter.name)}, in: ${JSON.stringify(parameter.in)}, style: ${JSON.stringify(parameter.style)}, explode: ${parameter.explode}, allowReserved: ${parameter.allowReserved}, required: ${required} }`
      );
      const doc = docComment([parameter.description, parameter.deprecated ? "@deprecated" : null], "  ");
      paramFields.push(`${doc}  ${propertyKey(key)}${required ? "" : "?"}: ${clientTypes.type(parameter.schema, "  ")};\n`);
    }
    if (shape.body) {
      const bodyType =
        shape.body.kind === "json" ? clientTypes.type(shape.body.schema, "  ") : shape.body.kind === "text" ? "string" : "Uint8Array | ArrayBuffer | Blob | ReadableStream<Uint8Array>";
      paramFields.push(`  body${shape.body.required ? "" : "?"}: ${bodyType};\n`);
    }
    const paramsRequired = operation.parameters.some((parameter) => parameter.in === "path" || parameter.required) || shape.body?.required === true;

    const terms = shape.security.map((alternative) =>
      `[${alternative
        .map((term) => {
          schemes.set(term.scheme, term.type === "apiKey" ? `API key sent in the ${term.in} "${term.name}"` : term.type === "basic" ? "HTTP Basic username and password" : "Bearer token");
          return term.type === "apiKey"
            ? `{ scheme: ${JSON.stringify(term.scheme)}, type: "apiKey", in: ${JSON.stringify(term.in)}, name: ${JSON.stringify(term.name)} }`
            : `{ scheme: ${JSON.stringify(term.scheme)}, type: ${JSON.stringify(term.type)} }`;
        })
        .join(", ")}]`
    );
    const retry = isReadMethod(operation.method) ? "read" : options.retry.idempotentOperations.includes(operation.id) ? "idempotent" : "never";
    const kinds = (response: ResponseShape) => `[${response.kinds.map((kind) => JSON.stringify(kind)).join(", ")}]`;
    specs.push(
      [
        `  ${JSON.stringify(operation.id)}: {`,
        `    id: ${JSON.stringify(operation.id)},`,
        `    name: ${JSON.stringify(operation.name)},`,
        `    method: ${JSON.stringify(operation.method.toUpperCase())},`,
        `    path: ${JSON.stringify(operation.path)},`,
        `    parameters: [${paramSpecs.length > 0 ? `\n      ${paramSpecs.join(",\n      ")},\n    ` : ""}],`,
        `    body: ${shape.body ? `{ mediaType: ${JSON.stringify(shape.body.mediaType)}, kind: ${JSON.stringify(shape.body.kind)}, required: ${shape.body.required} }` : "null"},`,
        `    accept: ${JSON.stringify(shape.accept)},`,
        `    success: ${shape.success ? kinds(shape.success) : "null"},`,
        `    errors: [${shape.errors.map((entry) => `{ status: ${JSON.stringify(entry.status)}, kinds: ${kinds(entry.shape)} }`).join(", ")}],`,
        `    security: [${terms.join(", ")}],`,
        `    retry: ${JSON.stringify(retry)},`,
        `  },`,
      ].join("\n")
    );

    const resultType = shape.success ? responseType(shape.success, clientTypes) : "unknown";
    const errorTypes = shape.errors.map(({ status, shape: response }) => {
      // Exact codes are literal types; ranges and default cover many statuses.
      const code = /^[1-5]\d\d$/.test(status) ? status : "number";
      return `ApiHttpError<${code}, ${responseType(response, clientTypes)}, true>`;
    });
    errorTypes.push("ApiHttpError<number, unknown, false>");
    const deprecation = operation.deprecation;
    const deprecated = deprecation.deprecated
      ? `@deprecated${deprecation.message ? ` ${deprecation.message}` : ""}${deprecation.replacement ? ` Use ${context.operations.find((candidate) => candidate.id === deprecation.replacement)?.name ?? deprecation.replacement} instead.` : ""}`
      : null;
    declarations.push(
      `${docComment([`Parameters of {@link ${options.clientName}.${operation.name}}.`])}export interface ${prefix}Params {\n${paramFields.join("")}}\n\n` +
        `export type ${prefix}Result = ${resultType};\n\n` +
        `export type ${prefix}Error =\n  | ${errorTypes.join("\n  | ")};\n`
    );
    errorEntries.push(`  ${JSON.stringify(operation.id)}: ${prefix}Error;\n`);
    methods.push(
      `${docComment([operation.summary, operation.description, `\`${operation.method.toUpperCase()} ${operation.path}\` (operation ${operation.id}).`, deprecated], "  ")}` +
        `  ${operation.name}(params: ${prefix}Params${paramsRequired ? "" : " = {}"}, options?: RequestOptions): Promise<${prefix}Result> {\n` +
        `    return this.#runtime.request(OPERATIONS[${JSON.stringify(operation.id)}], params as unknown as Record<string, unknown>, options) as Promise<${prefix}Result>;\n` +
        `  }\n`
    );
  }
  for (const scheme of [...unsupportedSchemes].sort()) {
    diagnostics.push({
      code: "SDK_UNSUPPORTED_SECURITY_SCHEME",
      severity: "warning",
      message: `Security scheme "${scheme}" cannot be injected by the TypeScript client; alternatives that need it are not used.`,
      pointer: `/securitySchemes/${scheme.replace(/~/g, "~0").replace(/\//g, "~1")}`,
    });
  }

  const credentialFields = [...schemes.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([scheme, description]) => {
      const type = description.startsWith("HTTP Basic") ? "CredentialSource<BasicCredential>" : "CredentialSource";
      return `${docComment([`${description} (security scheme ${scheme}).`], "  ")}  ${propertyKey(scheme)}?: ${type};\n`;
    });
  const metadata = {
    apiId: catalog.api.id,
    apiVersion: catalog.api.version,
    catalogDigest: context.catalogDigest,
    releaseId: context.releaseId,
    target: context.target.id,
    packageName: options.package.name,
    packageVersion: options.package.version,
    defaultBaseUrl: options.baseUrl,
    defaultTimeoutMs: options.timeoutMs,
    defaultRetry: { maxAttempts: options.retry.maxAttempts, baseDelayMs: options.retry.baseDelayMs, maxDelayMs: options.retry.maxDelayMs },
  };
  const client = options.clientName;
  const clientSource =
    header(context) +
    `\nimport { ApiHttpError, ApiRuntime, type BasicCredential, type ClientOptions, type CredentialSource, type OperationSpec, type RequestOptions, type SdkMetadata } from "./runtime.js";\n` +
    `import type * as Models from "./models.js";\n\n` +
    `const METADATA: SdkMetadata = ${JSON.stringify(metadata, null, 2)};\n\n` +
    `const OPERATIONS: Record<string, OperationSpec> = {\n${specs.join("\n")}\n};\n\n` +
    `${docComment([`Credentials by security scheme. Each request uses the first alternative its operation accepts whose credentials are all set; with none, it is sent without credentials.`])}` +
    `export interface ${client}Credentials {\n${credentialFields.join("")}}\n\n` +
    `export type ${client}Options = ClientOptions<${client}Credentials>${options.baseUrl === null ? " & { baseUrl: string }" : ""};\n\n` +
    declarations.join("\n") +
    `\n${docComment(["Typed HTTP errors by operation ID."])}export interface OperationErrors {\n${errorEntries.join("")}}\n\n` +
    `${docComment(["Narrows an error thrown by a client method to that operation's typed HTTP errors."])}` +
    `export function isOperationError<Id extends keyof OperationErrors>(error: unknown, operationId: Id): error is OperationErrors[Id] {\n` +
    `  return error instanceof ApiHttpError && error.operationId === operationId;\n}\n\n` +
    `${docComment([catalog.api.title, `Client for ${catalog.api.id} ${catalog.api.version}. Requests go only to the configured base URL; spec servers are never used.`])}` +
    `export class ${client} {\n  readonly #runtime: ApiRuntime<${client}Credentials>;\n\n` +
    `  constructor(options: ${client}Options${options.baseUrl === null ? "" : " = {}"}) {\n    this.#runtime = new ApiRuntime(METADATA, options);\n  }\n` +
    (methods.length > 0 ? `\n${methods.join("\n")}` : "") +
    `}\n`;

  const index =
    header(context) +
    `\nexport { ApiAbortError, ApiError, ApiHttpError, ApiTimeoutError } from "./runtime.js";\n` +
    `export type { ApiFailureKind, BasicCredential, ClientFailureObservation, ClientOptions, CredentialSource, RequestOptions, RetryOptions } from "./runtime.js";\n` +
    `export * from "./models.js";\nexport * from "./client.js";\nexport * from "./custom/index.js";\n`;

  const files: SdkFile[] = [
    { path: "package.json", contents: packageJson(options), ownership: "generated" },
    { path: "tsconfig.json", contents: TSCONFIG, ownership: "generated" },
    { path: "README.md", contents: readme(context), ownership: "generated" },
    { path: "src/runtime.ts", contents: RUNTIME_SOURCE, ownership: "generated" },
    { path: "src/models.ts", contents: models, ownership: "generated" },
    { path: "src/client.ts", contents: clientSource, ownership: "generated" },
    { path: "src/index.ts", contents: index, ownership: "generated" },
    { path: `${CUSTOM_CODE_ROOT}index.ts`, contents: CUSTOM_SEED, ownership: "seed" },
  ];
  return { files, diagnostics };
}

function packageJson(options: TypeScriptOptions): string {
  const pkg: Record<string, unknown> = { name: options.package.name, version: options.package.version };
  if (options.package.description !== null) pkg.description = options.package.description;
  if (options.package.license !== null) pkg.license = options.package.license;
  Object.assign(pkg, {
    type: "module",
    sideEffects: false,
    main: "./dist/index.js",
    types: "./dist/index.d.ts",
    exports: { ".": { types: "./dist/index.d.ts", default: "./dist/index.js" }, "./package.json": "./package.json" },
    files: ["dist", "apifn.sdk-manifest.json"],
    scripts: { build: "tsc -p tsconfig.json", typecheck: "tsc -p tsconfig.json --noEmit", prepack: "npm run build" },
    devDependencies: { typescript: TYPESCRIPT_VERSION },
    engines: { node: ">=18" },
  });
  return `${JSON.stringify(pkg, null, 2)}\n`;
}

const TSCONFIG = `${JSON.stringify(
  {
    compilerOptions: {
      target: "ES2022",
      module: "NodeNext",
      moduleResolution: "NodeNext",
      lib: ["ES2022", "DOM"],
      types: [],
      strict: true,
      declaration: true,
      rootDir: "src",
      outDir: "dist",
      skipLibCheck: true,
      forceConsistentCasingInFileNames: true,
    },
    include: ["src"],
  },
  null,
  2
)}\n`;

const CUSTOM_SEED = `// Custom code for this SDK. Files under ${CUSTOM_CODE_ROOT} are never rewritten or deleted by
// \`apifn sdk generate\`; this file was created once. Its exports are re-exported from the package entry.
export {};
`;

function readme(context: SdkTargetContext<TypeScriptOptions>): string {
  const { catalog, options } = context;
  const first = context.operations[0] as CatalogOperation | undefined;
  return `# ${options.package.name}

TypeScript client for ${catalog.api.id} ${catalog.api.version}, generated by ${context.generator.name} ${context.generator.version} from catalog \`${context.catalogDigest}\`. Do not edit generated files; put custom code in \`${CUSTOM_CODE_ROOT}\`.

\`\`\`ts
import { ${options.clientName} } from "${options.package.name}";

const client = new ${options.clientName}({${options.baseUrl === null ? ' baseUrl: "https://api.example.com",' : ""} credentials: { /* by security scheme */ } });
${first ? `const result = await client.${first.name}(/* params */);\n` : ""}\`\`\`

- Requests go only to \`baseUrl\` (${options.baseUrl === null ? "required" : `default \`${options.baseUrl}\``}); spec servers are never used and redirects are not followed.
- Non-2xx responses throw \`ApiHttpError\`; use \`isOperationError(error, operationId)\` for typed bodies. Timeouts throw \`ApiTimeoutError\`, aborted calls \`ApiAbortError\`.
- Reads are retried up to ${options.retry.maxAttempts} attempts on network errors, timeouts and HTTP 408, 429, 500, 502, 503 and 504; writes only when declared idempotent.
- \`onFailure\` receives an apifn.client-failure/v1 observation per failed call; nothing is observed unless it is set.

Provenance is in \`apifn.sdk-manifest.json\`.
`;
}
