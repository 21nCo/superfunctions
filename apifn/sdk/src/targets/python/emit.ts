import { compareCodeUnits } from "../../paths.js";
import type { SdkDiagnostic, SdkFile, SdkTargetContext, SdkTargetOutput } from "../../types.js";
import type { ResponseShape } from "../typescript/operations.js";
import { isReadMethod, suppliedByCredential } from "../typescript/operations.js";
import { aliasCuts, allAliasCuts, MAX_ALIAS_DEPTH } from "../typescript/schema.js";
import { NameRegistry } from "../typescript/naming.js";
import { pyComment, pyDocstring, pyPascalCase, pyString, PYTHON_KEYWORDS, snakeCase } from "./naming.js";
import { analyzePythonOperation } from "./operations.js";
import type { PythonOptions } from "./options.js";
import { PYTHON_RUNTIME_SOURCE } from "./runtime-source.js";
import { ANY, NEVER, type PyField, PythonTypes } from "./schema.js";

/** The custom-code directory: inside the import package, so its modules install with it. */
export function customCodeRoot(options: PythonOptions): string {
  return `src/${options.module}/custom/`;
}

/** Build backend and runtime dependencies of generated packages; pinned so builds are reproducible. */
export const HATCHLING_VERSION = "1.32.4";
export const HTTPX_REQUIREMENT = "httpx>=0.28.1,<0.29";
export const TYPING_EXTENSIONS_REQUIREMENT = "typing-extensions>=4.12,<5";

/** Names the package entry exports from the runtime. */
const RUNTIME_EXPORTS = [
  "ApiError",
  "ApiFailureKind",
  "ApiHttpError",
  "ApiTimeoutError",
  "BasicCredential",
  "ClientFailureObservation",
  "CredentialSource",
  "Headers",
  "HttpxTransport",
  "RequestOptions",
  "RetryOptions",
  "Transport",
  "TransportRequest",
  "TransportResponse",
];

/**
 * Client members besides the operation methods: a method with one of these names would replace them. Every
 * other attribute Python itself uses has leading underscores, which generated method names never have.
 */
const CLIENT_MEMBERS = new Map<string, string>([["aclose", "the method that closes the client's transport"]]);

/**
 * Builtins the client class's annotations name. Type checkers resolve those annotations in the class body, where a
 * method of the same name would replace the builtin, so when an operation method has one of these names the
 * client module writes them all through `builtins`.
 */
const ANNOTATION_BUILTINS = new Set(["bool", "bytearray", "bytes", "dict", "float", "int", "list", "memoryview", "object", "str"]);

/**
 * Whether the catalog declares that the server makes repeated calls of a write operation safe. Catalog v1
 * has no such field (method, schema and an `Idempotency-Key` parameter grant none), so no write is
 * retried; a later catalog version supplies the declaration here, not the SDK config.
 */
function declaresIdempotency(_operation: CatalogOperation): boolean {
  return false;
}

function header(context: SdkTargetContext<PythonOptions>): string {
  return `# Generated by ${context.generator.name} ${context.generator.version} (target ${context.target.id} ${context.target.version}). Do not edit: regeneration replaces this file.\n`;
}

const pointerOf = (name: string) => name.replace(/~/g, "~0").replace(/\//g, "~1");

function responseType(shape: ResponseShape, types: PythonTypes, owner: string, builtin: (name: string) => string): string {
  const members = shape.contents.map(({ kind, schema }) => (kind === "json" ? types.type(schema, owner) : kind === "text" ? builtin("str") : kind === "binary" ? builtin("bytes") : "None"));
  const unique = [...new Set(members)];
  if (unique.includes(ANY)) return ANY;
  return unique.join(" | ") || ANY;
}

function typedDict(name: string, fields: PyField[], total = true): string {
  const entries = fields.map((field) => {
    const doc = pyComment([field.description, field.deprecated ? "Deprecated." : null], "        ");
    const type = field.required || !total ? pyString(field.type) : `_te.NotRequired[${pyString(field.type)}]`;
    return `${doc}        ${pyString(field.key)}: ${type},\n`;
  });
  return `${name} = _te.TypedDict(\n    ${pyString(name)},\n    {\n${entries.join("")}    },${total ? "" : "\n    total=False,"}\n)\n`;
}

function list(values: string[], indent: string): string {
  return values.length === 0 ? "[]" : `[\n${values.map((value) => `${indent}    ${value},\n`).join("")}${indent}]`;
}

export function emitPython(context: SdkTargetContext<PythonOptions>): SdkTargetOutput {
  const { catalog, options } = context;
  const diagnostics: SdkDiagnostic[] = [];
  // Names the package entry exports, which are also the public names of models.py and client.py.
  const names = new NameRegistry();
  const claim = (name: string, owner: string, pointer?: string, operation?: string) => {
    const previous = PYTHON_KEYWORDS.has(name) ? "a Python keyword" : names.claim(name, owner);
    if (previous !== null) {
      diagnostics.push({
        code: "SDK_NAME_COLLISION",
        severity: "error",
        message: `Exported name "${name}" is generated for both ${previous} and ${owner}; rename one (options.typeNames for component schemas, options.clientName for the client, the manifest's name for operations).`,
        pointer,
        operation,
      });
    }
  };
  for (const name of RUNTIME_EXPORTS) claim(name, `the runtime export ${name}`);
  claim(options.clientName, "the client class", "/options/clientName");
  claim(`${options.clientName}Credentials`, "the client credentials type", "/options/clientName");
  claim("OperationId", "the operation ID type");
  claim("is_operation_error", "the operation error guard");
  claim("is_declared_error", "the declared operation error guard");

  // Models: every component schema the catalog publishes, sorted by name.
  const schemaNames = Object.keys(catalog.schemas).sort(compareCodeUnits);
  const typeNames = new Map<string, string>();
  for (const schema of schemaNames) {
    const typeName = Object.prototype.hasOwnProperty.call(options.typeNames, schema) ? options.typeNames[schema]! : pyPascalCase(schema);
    typeNames.set(schema, typeName);
    claim(typeName, `component schema "${schema}"`, `/schemas/${pointerOf(schema)}`);
  }
  // A cycle of references outside object and plain array types would be a type alias that refers to itself,
  // which type checkers reject; such references are typed Any, as the TypeScript target types them unknown.
  const found = aliasCuts(catalog.schemas);
  const listed = (targets: string[]) => targets.map((target) => `"${target}"`).join(", ");
  const which = (targets: string[]) => (targets.length === 1 ? "that reference is" : "those references are");
  for (const [schema, targets] of found.cycles) {
    diagnostics.push({
      code: "SDK_SCHEMA_CYCLE",
      severity: "warning",
      message: `Component schema "${schema}" refers back to ${listed(targets)} outside any object or plain array type, which a Python type alias cannot express; ${which(targets)} typed Any.`,
      pointer: `/schemas/${pointerOf(schema)}`,
    });
  }
  for (const [schema, targets] of found.depth) {
    diagnostics.push({
      code: "SDK_SCHEMA_DEPTH",
      severity: "warning",
      message: `Component schema "${schema}" refers to ${listed(targets)} outside any object or plain array type at the start of a chain of such references more than ${MAX_ALIAS_DEPTH} levels deep; ${which(targets)} typed Any.`,
      pointer: `/schemas/${pointerOf(schema)}`,
    });
  }
  const cuts = allAliasCuts(found);
  const resolve = (component: string) => typeNames.get(component) ?? null;
  const taken = new Set<string>(typeNames.values());
  const modelTypes = new PythonTypes(catalog.schemas, resolve, cuts, "", taken);
  const shadowsBuiltins = context.operations.some((operation) => ANNOTATION_BUILTINS.has(snakeCase(operation.name)));
  const b = (name: string) => (shadowsBuiltins ? `_b.${name}` : name);
  const clientTypes = modelTypes.withPrefix("_m.", b);

  const modelDefinitions: string[] = [];
  for (const schema of schemaNames) {
    const value = catalog.schemas[schema];
    const typeName = typeNames.get(schema)!;
    const cut = cuts.get(schema);
    const description = typeof value === "object" && value !== null && !Array.isArray(value) && typeof value.description === "string" ? value.description : null;
    const fields = modelTypes.objectFields(value, typeName, cut);
    const definition = fields !== null ? typedDict(typeName, fields) : `${typeName}: _te.TypeAlias = ${pyString(modelTypes.type(value, typeName, 0, cut))}\n`;
    modelDefinitions.push(`${pyComment([description])}${definition}`);
  }

  // Operations.
  const schemes = new Map<string, string>();
  const specs: string[] = [];
  const aliases: string[] = [];
  const methods: string[] = [];
  const declaredOverloads: Array<{ id: string; body: string }> = [];
  const methodNames = new NameRegistry();
  for (const [name, owner] of CLIENT_MEMBERS) methodNames.claim(name, owner);
  const unsupportedSchemes = new Set<string>();
  const runtimeUses = new Set<string>();
  for (const operation of context.operations) {
    const shape = analyzePythonOperation(operation, catalog);
    const pointer = `/operations/${catalog.operations.indexOf(operation)}`;
    shape.unsupportedSchemes.forEach((scheme) => unsupportedSchemes.add(scheme));
    if (operation.servers !== null) {
      diagnostics.push({
        code: "SDK_SERVERS_IGNORED",
        severity: "warning",
        message: `${operation.id} declares its own servers; the client sends it to the configured base URL like every other operation.`,
        pointer: `${pointer}/servers`,
        operation: operation.id,
      });
    }
    const prefix = pyPascalCase(operation.name);
    const owner = `operation ${operation.id}`;
    const method = snakeCase(operation.name);
    const previousMethod = methodNames.claim(method, owner);
    if (previousMethod !== null) {
      diagnostics.push({
        code: "SDK_NAME_COLLISION",
        severity: "error",
        message: `${operation.id}: method name "${method}" is also ${previousMethod}; set another name in the manifest.`,
        pointer: `${pointer}/name`,
        operation: operation.id,
      });
    }
    for (const suffix of ["Result", "ErrorBody"]) claim(`${prefix}${suffix}`, owner, `${pointer}/name`, operation.id);

    // Parameters become keyword-only arguments in snake_case, next to `body` and `request_options`.
    const keys = new Map<string, string>([["request_options", "the request options argument"]]);
    if (shape.body) keys.set("body", "the request body");
    const paramSpecs: string[] = [];
    const required: string[] = [];
    const optional: string[] = [];
    const values: string[] = [];
    const argumentDocs: string[] = [];
    for (const [position, parameter] of operation.parameters.entries()) {
      const key = snakeCase(parameter.name);
      const previous = keys.get(key);
      if (previous !== undefined) {
        diagnostics.push({
          code: "SDK_NAME_COLLISION",
          severity: "error",
          message: `${operation.id}: ${parameter.in} parameter "${parameter.name}" and ${previous} both become the argument "${key}".`,
          pointer: `${pointer}/parameters/${position}`,
          operation: operation.id,
        });
      }
      keys.set(key, `${parameter.in} parameter "${parameter.name}"`);
      const isRequired = parameter.in === "path" || parameter.required;
      paramSpecs.push(
        `_ParameterSpec(key=${pyString(key)}, name=${pyString(parameter.name)}, location=${pyString(parameter.in)}, style=${pyString(parameter.style)}, explode=${parameter.explode ? "True" : "False"}, allow_reserved=${parameter.allowReserved ? "True" : "False"}, required=${isRequired ? "True" : "False"})`
      );
      const credential = suppliedByCredential(parameter, shape.security);
      // A type that also admits values the client cannot serialize is narrowed to the ones it can.
      const narrowing = shape.parameters[position];
      if (narrowing !== null && narrowing !== undefined) runtimeUses.add(narrowing === "value" ? "ParamValue" : "DeepObjectValue");
      const type = narrowing === "value" ? "_ParamValue" : narrowing === "deepObject" ? "_DeepObjectValue" : clientTypes.type(parameter.schema, prefix, 0, undefined, "direct", true);
      if (isRequired && !credential) required.push(`${key}: ${type}`);
      else optional.push(`${key}: ${type === ANY ? ANY : `${type} | None`} = None`);
      values.push(`${pyString(key)}: ${key}`);
      const notes = [parameter.description, isRequired && credential ? "Required unless the API key credential sent under this name is applied." : null, parameter.deprecated ? "Deprecated." : null].filter(
        (note): note is string => typeof note === "string" && note.trim() !== ""
      );
      argumentDocs.push(`${key}: ${parameter.in} parameter ${parameter.name}${notes.length > 0 ? `. ${notes.join(" ")}` : ""}`);
    }
    if (shape.body) {
      const bodyType =
        shape.body.kind === "json"
          ? clientTypes.type(shape.body.schema, prefix)
          : shape.body.kind === "text"
            ? b("str")
            : `${b("bytes")} | ${b("bytearray")} | ${b("memoryview")} | _t.AsyncIterable[${b("bytes")}]`;
      // An optional body left out sends none; None is a value (a JSON null), as undefined and null are in TypeScript.
      if (shape.body.required) required.push(`body: ${bodyType}`);
      else {
        runtimeUses.add("OMITTED").add("Omitted");
        optional.push(`body: ${bodyType === ANY ? ANY : `${bodyType} | _Omitted`} = _OMITTED`);
      }
      values.push(`"body": body`);
      argumentDocs.push(`body: request body sent as ${shape.body.mediaType}${shape.body.required ? "" : "; left out, none is sent"}.`);
    }

    const terms = shape.security.map(
      (alternative) =>
        `(${alternative
          .map((term) => {
            schemes.set(term.scheme, term.type === "apiKey" ? `API key sent in the ${term.in} "${term.name}"` : term.type === "basic" ? "HTTP Basic username and password" : "Bearer token");
            return term.type === "apiKey"
              ? `_SecurityTerm(scheme=${pyString(term.scheme)}, type="apiKey", location=${pyString(term.in)}, name=${pyString(term.name)})`
              : `_SecurityTerm(scheme=${pyString(term.scheme)}, type=${pyString(term.type)})`;
          })
          .join(", ")}${alternative.length === 1 ? "," : ""})`
    );
    const retry = isReadMethod(operation.method) ? "read" : declaresIdempotency(operation) ? "idempotent" : "never";
    const kinds = (response: ResponseShape) => `(${response.kinds.map((kind) => pyString(kind)).join(", ")}${response.kinds.length === 1 ? "," : ""})`;
    const tuple = (items: string[], indent: string) => (items.length === 0 ? "()" : `(\n${items.map((item) => `${indent}    ${item},\n`).join("")}${indent})`);
    specs.push(
      [
        `    ${pyString(operation.id)}: _OperationSpec(`,
        `        id=${pyString(operation.id)},`,
        `        name=${pyString(operation.name)},`,
        `        method=${pyString(operation.method.toUpperCase())},`,
        `        path=${pyString(operation.path)},`,
        `        parameters=${tuple(paramSpecs, "        ")},`,
        `        body=${shape.body ? `_BodySpec(media_type=${pyString(shape.body.mediaType)}, kind=${pyString(shape.body.kind)}, required=${shape.body.required ? "True" : "False"})` : "None"},`,
        `        accept=${tuple(shape.accept.map(pyString), "        ")},`,
        `        success=${shape.success ? kinds(shape.success) : "None"},`,
        `        errors=${tuple(shape.errors.map((entry) => `_ErrorSpec(status=${pyString(entry.status)}, kinds=${kinds(entry.shape)})`), "        ")},`,
        `        security=${tuple(terms, "        ")},`,
        `        retry=${pyString(retry)},`,
        `    ),`,
      ].join("\n")
    );

    const resultType = shape.success ? responseType(shape.success, clientTypes, prefix, b) : ANY;
    const errorBodies = [...new Set(shape.errors.map(({ shape: response }) => responseType(response, clientTypes, prefix, b)))];
    const errorBody = errorBodies.length === 0 ? NEVER : errorBodies.includes(ANY) ? ANY : errorBodies.join(" | ");
    aliases.push(`${prefix}Result: _te.TypeAlias = ${pyString(resultType)}\n${prefix}ErrorBody: _te.TypeAlias = ${pyString(errorBody)}\n`);
    declaredOverloads.push({ id: operation.id, body: `${prefix}ErrorBody` });

    const deprecation = operation.deprecation;
    const replacement = deprecation.replacement ? context.operations.find((candidate) => candidate.id === deprecation.replacement) : undefined;
    const deprecatedText = deprecation.deprecated
      ? [deprecation.message, deprecation.replacement ? `Use ${replacement ? snakeCase(replacement.name) : deprecation.replacement} instead.` : null].filter(Boolean).join(" ") || "Deprecated."
      : null;
    const doc = pyDocstring(
      [
        operation.summary,
        operation.description,
        `${operation.method.toUpperCase()} ${operation.path} (operation ${operation.id}).`,
        deprecatedText ? `Deprecated: ${deprecatedText}` : null,
        argumentDocs.length > 0 ? `Arguments:\n${argumentDocs.map((line) => `    ${line}`).join("\n")}` : null,
      ],
      "        "
    );
    const signature = ["self", "*", ...required, ...optional, "request_options: _RequestOptions | None = None"];
    methods.push(
      `${deprecatedText ? `    @_te.deprecated(${pyString(deprecatedText)})\n` : ""}` +
        `    async def ${method}(\n${signature.map((part) => `        ${part},\n`).join("")}    ) -> ${prefix}Result:\n` +
        doc +
        `        return _t.cast(\n            ${pyString(`${prefix}Result`)},\n            await self._runtime.request(_OPERATIONS[${pyString(operation.id)}], {${values.join(", ")}}, request_options),\n        )\n`
    );
  }
  for (const scheme of [...unsupportedSchemes].sort(compareCodeUnits)) {
    diagnostics.push({
      code: "SDK_UNSUPPORTED_SECURITY_SCHEME",
      severity: "warning",
      message: `Security scheme "${scheme}" cannot be injected by the Python client; alternatives that need it are not used.`,
      pointer: `/securitySchemes/${pointerOf(scheme)}`,
    });
  }

  const client = options.clientName;
  const credentialFields: PyField[] = [...schemes.entries()]
    .sort(([a], [b]) => compareCodeUnits(a, b))
    .map(([scheme, description]) => ({
      key: scheme,
      type: description.startsWith("HTTP Basic") ? "_CredentialSource[_BasicCredential]" : "_CredentialSource[str]",
      required: false,
      description: `${description} (security scheme ${scheme}).`,
      deprecated: false,
    }));
  const metadata = [
    `    api_id=${pyString(catalog.api.id)},`,
    `    api_version=${pyString(catalog.api.version)},`,
    `    catalog_digest=${pyString(context.catalogDigest)},`,
    `    release_id=${pyString(context.releaseId)},`,
    `    target=${pyString(context.target.id)},`,
    `    package_name=${pyString(options.package.name)},`,
    `    package_version=${pyString(options.package.version)},`,
    `    default_base_url=${options.baseUrl === null ? "None" : pyString(options.baseUrl)},`,
    `    default_timeout=${options.timeoutMs / 1000},`,
    `    default_retry=_RetryPolicy(max_attempts=${options.retry.maxAttempts}, base_delay=${options.retry.baseDelayMs / 1000}, max_delay=${options.retry.maxDelayMs / 1000}),`,
  ];
  const ids = context.operations.map((operation) => pyString(operation.id));
  const operationId = ids.length === 0 ? "str" : `_t.Literal[${ids.join(", ")}]`;
  let declared: string;
  const guardDoc = pyDocstring(["Whether `error` is an HTTP error the operation documents (status and body kind), narrowing its body to the documented types."], "    ");
  if (declaredOverloads.length >= 2) {
    declared =
      declaredOverloads
        .map(({ id, body }) => `@_t.overload\ndef is_declared_error(error: object, operation_id: _t.Literal[${pyString(id)}]) -> _te.TypeGuard[_ApiHttpError[${body}]]: ...\n`)
        .join("") +
      `def is_declared_error(error: object, operation_id: str) -> bool:\n${guardDoc}    return isinstance(error, _ApiHttpError) and error.operation_id == operation_id and error.declared\n`;
  } else {
    const only = declaredOverloads[0];
    declared = `def is_declared_error(error: object, operation_id: ${only ? `_t.Literal[${pyString(only.id)}]` : "str"}) -> _te.TypeGuard[_ApiHttpError[${only ? only.body : "_t.Any"}]]:\n${guardDoc}    return isinstance(error, _ApiHttpError) and error.operation_id == operation_id and error.declared\n`;
  }
  const exportedClient = [client, `${client}Credentials`, "OperationId", ...context.operations.flatMap((operation) => [`${pyPascalCase(operation.name)}Result`, `${pyPascalCase(operation.name)}ErrorBody`]), "is_declared_error", "is_operation_error"].sort(compareCodeUnits);
  const runtimeImports = [
    "ApiHttpError",
    "ApiRuntime",
    "BasicCredential",
    "BodySpec",
    "ClientFailureObservation",
    "CredentialSource",
    "ErrorSpec",
    "OperationSpec",
    "ParameterSpec",
    "RequestOptions",
    "RetryOptions",
    "RetryPolicy",
    "SdkMetadata",
    "SecurityTerm",
    "Transport",
    ...runtimeUses,
  ].sort(compareCodeUnits);
  const constructorArguments = [
    "self",
    "*",
    `base_url: ${b("str")}${options.baseUrl === null ? "" : " | None = None"}`,
    "transport: _Transport | None = None",
    `credentials: ${client}Credentials | None = None`,
    `timeout: ${b("float")} | None = None`,
    "retry: _RetryOptions | None = None",
    `on_failure: _t.Callable[[_ClientFailureObservation], ${b("object")}] | None = None`,
  ];
  const clientSource =
    header(context) +
    `\nfrom __future__ import annotations\n\n${shadowsBuiltins ? "import builtins as _b\n" : ""}import typing as _t\n\nimport typing_extensions as _te\n\nfrom . import models as _m\nfrom ._runtime import (\n${runtimeImports.map((name) => `    ${name} as _${name},\n`).join("")})\n\n` +
    `__all__ = ${list(exportedClient.map(pyString), "")}\n\n` +
    `_METADATA = _SdkMetadata(\n${metadata.join("\n")}\n)\n\n` +
    `_OPERATIONS: dict[str, _OperationSpec] = {\n${specs.join("\n")}\n}\n\n` +
    `${pyComment(["Credentials by security scheme. Each request uses the first credentialed alternative its operation accepts whose credentials are all set; otherwise it is sent without credentials."])}` +
    typedDict(`${client}Credentials`, credentialFields, false) +
    `\nOperationId: _te.TypeAlias = ${pyString(operationId)}\n\n` +
    aliases.join("\n") +
    `\n\ndef is_operation_error(error: object, operation_id: OperationId) -> _te.TypeGuard[_ApiHttpError[object]]:\n` +
    pyDocstring(["Whether `error` is an HTTP error a method of this client raised for the operation, documented or not."], "    ") +
    `    return isinstance(error, _ApiHttpError) and error.operation_id == operation_id\n\n\n` +
    declared +
    `\n\nclass ${client}:\n` +
    pyDocstring([catalog.api.title, `Client for ${catalog.api.id} ${catalog.api.version}. Requests go only to the configured base URL; spec servers are never used. Close it with aclose() or use it as an async context manager.`], "    ") +
    `\n    def __init__(\n${constructorArguments.map((part) => `        ${part},\n`).join("")}    ) -> None:\n` +
    `        self._runtime = _ApiRuntime(\n            _METADATA,\n            base_url=base_url,\n            transport=transport,\n            credentials=credentials,\n            timeout=timeout,\n            retry=retry,\n            on_failure=on_failure,\n        )\n\n` +
    `    async def __aenter__(self) -> _te.Self:\n        return self\n\n` +
    `    async def __aexit__(self, *exc_info: ${b("object")}) -> None:\n        await self.aclose()\n\n` +
    `    async def aclose(self) -> None:\n        """Closes the transport this client created; an injected transport is left open."""\n        await self._runtime.aclose()\n` +
    (methods.length > 0 ? `\n${methods.join("\n")}` : "");

  // models.py: component schemas, then the inline TypedDicts every module needed.
  const modelExports = schemaNames.map((schema) => typeNames.get(schema)!).sort(compareCodeUnits);
  const models =
    header(context) +
    `\nfrom __future__ import annotations\n\nimport typing as _t\n\nimport typing_extensions as _te\n\n` +
    `__all__ = ${list(modelExports.map(pyString), "")}\n` +
    modelDefinitions.map((definition) => `\n${definition}`).join("") +
    modelTypes.inlineTypedDicts().map(({ name, fields }) => `\n${typedDict(name, fields)}`).join("");

  const runtimeExports = RUNTIME_EXPORTS.map((name) => `    ${name} as ${name},\n`).join("");
  const exportedModels = modelExports.map((name) => `    ${name} as ${name},\n`).join("");
  const index =
    header(context) +
    `\nfrom ._runtime import (\n${runtimeExports})\n` +
    `from .client import (\n${exportedClient.map((name) => `    ${name} as ${name},\n`).join("")})\n` +
    (exportedModels ? `from .models import (\n${exportedModels})\n` : "") +
    // Custom code is imported last, so it can import the generated names from the package.
    `from . import custom as _custom\nfrom .custom import *  # noqa: F403\n\n` +
    `__all__ = ${list([...RUNTIME_EXPORTS, ...exportedClient, ...modelExports].sort(compareCodeUnits).map(pyString), "")}\n` +
    `__all__ += _custom.__all__\n`;

  const root = `src/${options.module}/`;
  const files: SdkFile[] = [
    { path: "pyproject.toml", contents: pyproject(context), ownership: "generated" },
    { path: "README.md", contents: readme(context), ownership: "generated" },
    { path: `${root}__init__.py`, contents: index, ownership: "generated" },
    { path: `${root}_runtime.py`, contents: PYTHON_RUNTIME_SOURCE, ownership: "generated" },
    { path: `${root}models.py`, contents: models, ownership: "generated" },
    { path: `${root}client.py`, contents: clientSource, ownership: "generated" },
    { path: `${root}py.typed`, contents: "", ownership: "generated" },
    { path: `${customCodeRoot(options)}__init__.py`, contents: customSeed(options), ownership: "seed" },
  ];
  return { files, diagnostics };
}

/** A TOML basic string of ASCII text: every other code point, and every character TOML gives meaning to, is escaped. */
function toml(value: string): string {
  let out = '"';
  for (const char of value) {
    const code = char.codePointAt(0)!;
    if (char === "\\") out += "\\\\";
    else if (char === '"') out += '\\"';
    else if (char === "\n") out += "\\n";
    else if (char === "\r") out += "\\r";
    else if (char === "\t") out += "\\t";
    else if (code >= 0x20 && code < 0x7f) out += char;
    else if (code <= 0xffff) out += `\\u${code.toString(16).padStart(4, "0")}`;
    else out += `\\U${code.toString(16).padStart(8, "0")}`;
  }
  return `${out}"`;
}

