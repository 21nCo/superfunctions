import assert from 'node:assert/strict';
import { createHmac } from 'node:crypto';
import { cachedSearch, cachedProfileRoute, cachedSlackHandler } from '../examples/ecosystem.js';
import { authfn } from 'authfn';
import { memoryAdapter } from '@superfunctions/db/testing';
import { createUser } from 'authfn/core/users';
import { issueSession } from 'authfn/core/sessions';
import { issueSessionCookies } from 'authfn/core/cookies';

const search = cachedSearch();
await search.index({ resource: 'articles', documents: [{ id: 'one', fields: { title: 'Caching browsers' } }] });
assert.deepEqual(await search.search({ resource: 'articles', query: 'caching' }), ['one']);
assert.deepEqual(await search.search({ resource: 'articles', query: 'caching' }), ['one']);
assert.equal((await search.cache.getStats()).hits, 1);
await search.index({ resource: 'articles', documents: [{ id: 'two', fields: { title: 'Caching servers' } }] });
assert.equal((await search.search({ resource: 'articles', query: 'caching' })).length, 2);
await search.remove('articles', ['one']);
assert.deepEqual(await search.search({ resource: 'articles', query: 'caching' }), ['two']);
await search.dispose();

const database = memoryAdapter({ debug: false });
const config = { plugins: [], database, namespace: 'cachefn-auth-example' };
const auth = authfn({ plugins: [], namespace: config.namespace }).createServer({ database });
const user = await createUser(config, { primaryEmail: 'cache@example.test' });
const issued = await issueSession(config, {}, { request: new Request('https://example.test/auth/session'), userId: user.id, methods: ['password'] });
const cookies = issueSessionCookies(issued.cookiePolicy!, issued.sessionToken, issued.csrfToken);
const cookie = Object.values(cookies).map(value => value.split(';')[0]).join('; ');
const request = () => new Request('https://example.test/profile', { headers: { cookie } });
let loads = 0;
const route = cachedProfileRoute(auth, async actorId => ({ actorId, revision: ++loads }));
assert.equal((await route.handle(new Request('https://example.test/profile'))).status, 401);
assert.equal((await (await route.handle(request())).json()).revision, 1);
assert.equal((await (await route.handle(request())).json()).revision, 1);
await auth.revokeSession(issued.session.id);
assert.equal((await route.handle(request())).status, 401);
assert.equal(loads, 1);

let processes = 0;
const secret = 'local-example-secret';
const slack = cachedSlackHandler(secret, async () => { processes++; });
const body = JSON.stringify({ event_id: 'event-1', event: { text: 'hello' } });
const timestamp = String(Math.floor(Date.now() / 1000));
const signature = `v0=${createHmac('sha256', secret).update(`v0:${timestamp}:${body}`).digest('hex')}`;
const signed = (signatureValue = signature) => new Request('https://example.test/slack', { method: 'POST', body, headers: { 'x-slack-request-timestamp': timestamp, 'x-slack-signature': signatureValue } });
const responses = await Promise.all([slack.handle(signed()), slack.handle(signed())]);
assert(responses.every(response => response.status === 200)); assert.equal(processes, 1);
assert.equal((await slack.handle(signed('v0=invalid'))).status, 401); assert.equal(processes, 1);
route.cache.dispose(); slack.cache.dispose();
console.log('SearchFn indexing/query invalidation, AuthFn fresh authentication/revocation, and BotFn Slack verification/deduplication passed');
