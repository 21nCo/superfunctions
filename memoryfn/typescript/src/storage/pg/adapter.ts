import {
  requireScope, requireSourceReplace, requireSourceScope,
  type StorageAdapter, type MemoryScope, type MemoryUpdate, type MemoryDelete, type MemoryInsert, type MemoryRelationshipInsert,
  type SourceReplace, type SourceScope, type SourceState,
} from '../adapter';
import { Memory, MemoryRelationship } from '../../core/types';
import { memories, memoryRelationships } from './schema';
import { and, eq, sql, isNull, or, arrayContains, inArray, is } from 'drizzle-orm';
import { PgTransaction } from 'drizzle-orm/pg-core';
import { PostgresJsDatabase } from 'drizzle-orm/postgres-js';

// We assume the DB passed is compatible with PostgresJsDatabase schema
export class PostgresAdapter implements StorageAdapter {
  readonly embeddingDimensions = 1536;
  private db: PostgresJsDatabase<any>;

  constructor(db: PostgresJsDatabase<any>, private readonly dispose?: () => Promise<void>) {
    this.db = db;
  }

  async transaction<T>(operation: (storage: StorageAdapter) => Promise<T>): Promise<T> {
    return this.db.transaction(tx => operation(new PostgresAdapter(tx as unknown as PostgresJsDatabase<any>)));
  }

  async close(): Promise<void> { await this.dispose?.(); }

  async insertMemories(memoryInputs: MemoryInsert[]): Promise<Memory[]> {
    if (memoryInputs.length === 0) return [];

    for (const input of memoryInputs) requireScope(input.tenantId, input.containerTags);
    const now = new Date();
    const values = memoryInputs.map(m => this.toRow(m, now));

    const result = await this.db.insert(memories)
      .values(values)
      .returning();

    return result.map(this.mapToDomain);
  }

  /** Maps a domain insert to schema values; source columns are never taken from the input. */
  private toRow(m: MemoryInsert, now: Date) {
    return {
      // id is autogenerated if not present, but we prefer letting DB generate it or using what's passed
      ...(m.id ? { id: m.id } : {}),
      tenantId: m.tenantId,
      containerTags: [...m.containerTags],
      type: m.type || 'conversational',
      content: m.content || '',
      embedding: m.embedding || null,
      metadata: m.metadata || {},
      isLatest: m.isLatest ?? true,
      createdAt: m.createdAt ? new Date(m.createdAt) : now,
      updatedAt: m.updatedAt ? new Date(m.updatedAt) : now,
    };
  }

  async insertRelationships(relationships: MemoryRelationshipInsert[]): Promise<MemoryRelationship[]> {
    if (relationships.length === 0) return [];
    for (const relationship of relationships) requireScope(relationship.tenantId, relationship.containerTags);

    const now = new Date();
    const values = relationships.map(r => ({
      ...(r.id ? { id: r.id } : {}),
      fromId: r.fromId,
      toId: r.toId,
      type: r.type || 'extends',
      confidence: r.confidence ?? 1.0,
      reasoning: r.reasoning,
      createdAt: r.createdAt ? new Date(r.createdAt) : now,
    }));

    const result = await this.db.transaction(async tx => {
      const ids = [...new Set(values.flatMap(value => [value.fromId, value.toId]))].sort((a, b) => a < b ? -1 : a > b ? 1 : 0);
      const rows = await tx.select().from(memories).where(and(inArray(memories.id, ids), isNull(memories.deletedAt))).orderBy(memories.id).for('update');
      const byId = new Map(rows.map(row => [row.id, row]));
      for (const [index, value] of values.entries()) {
        const from = byId.get(value.fromId); const to = byId.get(value.toId);
        const scope = relationships[index];
        const inScope = (memory: typeof from) => memory
          && memory.tenantId === scope.tenantId
          && scope.containerTags.every(tag => memory.containerTags.includes(tag));
        if (!inScope(from) || !inScope(to)) throw new Error('MEMORY_RELATION_SCOPE_INVALID');
      }
      return tx.insert(memoryRelationships).values(values).returning();
    }).catch(error => {
      const cause = error?.cause ?? error;
      if (cause?.code === "23505") throw new Error("MEMORY_RELATION_EXISTS", { cause: error });
      throw error;
    });

    return result.map(r => ({
      id: r.id,
      fromId: r.fromId,
      toId: r.toId,
      type: r.type as any,
      confidence: r.confidence,
      reasoning: r.reasoning || undefined,
      createdAt: r.createdAt.getTime(),
    }));
  }

  async searchVectors(params: {
    tenantId: string;
    embedding: number[];
    containerTags: string[];
    filters?: Record<string, any>;
    topK: number;
    threshold?: number;
  }): Promise<Memory[]> {
    requireScope(params.tenantId, params.containerTags);
    const { tenantId, embedding, containerTags, topK, threshold } = params;

    // pgvector cosine similarity operator is <=>
    // We want to sort by distance ascending (closest first)
    // distance = 1 - similarity
    // To filter by threshold (similarity), distance should be <= (1 - threshold)
    
    const similarity = sql<number>`1 - (${memories.embedding} <=> ${JSON.stringify(embedding)}::vector)`;
    
    let query = this.db.select({
      memory: memories,
      similarity: similarity
    })
    .from(memories);

    // Build Where Clauses
    const conditions = [eq(memories.tenantId, tenantId), isNull(memories.deletedAt), eq(memories.isLatest, true)];

    // All supplied tags constrain retrieval within the explicit tenant.
    if (containerTags && containerTags.length > 0) {
      conditions.push(arrayContains(memories.containerTags, containerTags));
    }

    if (threshold !== undefined) {
        conditions.push(sql`(${memories.embedding} <=> ${JSON.stringify(embedding)}::vector) <= ${1 - threshold}`);
    }

    if (params.filters) {
        // Simple metadata exact match support
        for (const [key, value] of Object.entries(params.filters)) {
            // JSONB containment @>
            conditions.push(sql`${memories.metadata} @> ${JSON.stringify({ [key]: value })}`);
        }
    }

    if (conditions.length > 0) {
        query = query.where(and(...conditions)) as any;
    }

    const results = await query
        .orderBy(sql`${memories.embedding} <=> ${JSON.stringify(embedding)}::vector ASC`)
        .limit(topK);

    return results.map(r => this.mapToDomain(r.memory));
  }


  private scope(input: MemoryScope & { id: string }) {
    requireScope(input.tenantId, input.containerTags);
    return and(eq(memories.id, input.id), eq(memories.tenantId, input.tenantId),
      input.containerTags.length ? arrayContains(memories.containerTags, input.containerTags) : undefined);
  }

  async getMemory(input: MemoryScope & { id: string }): Promise<Memory | null> {
    const [row] = await this.db.select().from(memories).where(and(this.scope(input), isNull(memories.deletedAt))).limit(1);
    return row ? this.mapToDomain(row) : null;
  }

  async updateMemory(input: MemoryUpdate): Promise<Memory> {
    const [row] = await this.db.update(memories).set({
      content: input.changes.content, embedding: input.changes.embedding,
      ...(input.changes.metadata === undefined ? {} : { metadata: input.changes.metadata }),
      ...(input.changes.isLatest === undefined ? {} : { isLatest: input.changes.isLatest }),
      revision: sql`${memories.revision} + 1`, updatedAt: new Date(),
    }).where(and(this.scope(input), isNull(memories.deletedAt), eq(memories.revision, input.expectedRevision))).returning();
    if (!row) throw new Error('MEMORY_REVISION_CONFLICT');
    return this.mapToDomain(row);
  }

  async deleteMemory(input: MemoryDelete): Promise<void> {
    const scope = this.scope(input);
    await this.db.transaction(async tx => {
      const [current] = await tx.select().from(memories).where(scope).for('update');
      if (!current) throw new Error('MEMORY_NOT_FOUND');
      if (current.deletedAt != null) return;
      if (input.expectedRevision !== undefined && current.revision !== input.expectedRevision) throw new Error('MEMORY_REVISION_CONFLICT');
      await tx.update(memories).set({ content: '', embedding: null, metadata: {}, isLatest: false,
        deletedAt: new Date(), updatedAt: new Date(), revision: sql`${memories.revision} + 1` }).where(scope);
      await tx.delete(memoryRelationships).where(or(eq(memoryRelationships.fromId, input.id), eq(memoryRelationships.toId, input.id)));
    });
  }

  /** Live chunks of exactly this tenant, tag set (as a set) and source key. */
  private liveSource(scope: SourceScope, tags: string[]) {
    const tagSet = sql`ARRAY(SELECT jsonb_array_elements_text(${JSON.stringify(tags)}::jsonb))::text[]`;
    return and(eq(memories.tenantId, scope.tenantId), eq(memories.sourceKey, scope.sourceKey), isNull(memories.deletedAt),
      sql`${memories.containerTags} @> ${tagSet}`, sql`${memories.containerTags} <@ ${tagSet}`);
  }

  /**
   * Runs `operation` in a transaction that holds the source's advisory lock until
   * the top-level transaction ends, so writes to one (tenant, source key) are
   * serialized across connections. A new transaction runs at READ COMMITTED, so
   * statements after the lock see chunks committed while it waited. A savepoint
   * inherits the enclosing isolation level, and any other level is rejected
   * before a write: its snapshot can predate the previous holder's commit.
   *
   * It then row-locks the source's live chunks (in id order, like
   * insertRelationships), waiting for any transaction that holds one, such as a
   * relationship insert. The write statement that follows therefore takes its
   * snapshot after that transaction committed and removes its relationships too;
   * later relationship inserts wait on the row lock and then find a tombstone.
   *
   * The advisory and row locks are re-entrant within one session, so they do not
   * order writes made through one transaction (by any adapter or savepoint on
   * it). `operation` must therefore make its whole change in one statement:
   * statements of one session run one at a time and each sees the session's
   * earlier writes.
   */
  private withSourceLock<T>(scope: SourceScope, tags: string[], operation: (tx: PostgresJsDatabase<any>) => Promise<T>): Promise<T> {
    const locked = async (tx: PostgresJsDatabase<any>) => {
      const [setting] = await tx.execute<{ isolation: string }>(sql`SELECT current_setting('transaction_isolation') AS isolation`);
      if (setting?.isolation !== 'read committed') throw new Error('MEMORY_SOURCE_ISOLATION_UNSUPPORTED');
      const key = JSON.stringify([scope.tenantId, scope.sourceKey]);
      await tx.execute(sql`SELECT pg_advisory_xact_lock(hashtextextended(${key}, 0))`);
      await tx.select({ id: memories.id }).from(memories).where(this.liveSource(scope, tags)).orderBy(memories.id).for('update');
      return operation(tx);
    };
    return is(this.db, PgTransaction)
      ? this.db.transaction(tx => locked(tx as unknown as PostgresJsDatabase<any>))
      : this.db.transaction(tx => locked(tx as unknown as PostgresJsDatabase<any>), { isolationLevel: 'read committed' });
  }

  /** Column values that clear and soft-delete a source chunk. */
  private tombstone(now: Date) {
    return { content: '', embedding: null, metadata: {}, isLatest: false, deletedAt: now, updatedAt: now, revision: sql`${memories.revision} + 1` };
  }

  /**
   * Common table expressions that clear and soft-delete every live chunk of the
   * source and drop their relationships. PostgreSQL runs data-modifying CTEs to
   * completion as part of the statement that carries them.
   */
  private tombstoneSource(tx: PostgresJsDatabase<any>, scope: SourceScope, tags: string[], now: Date) {
    const tombstoned = tx.$with('source_tombstoned').as(tx.update(memories).set(this.tombstone(now))
      .where(this.liveSource(scope, tags)).returning({ id: memories.id }));
    const ids = tx.select({ id: tombstoned.id }).from(tombstoned);
    const unlinked = tx.$with('source_unlinked').as(tx.delete(memoryRelationships)
      .where(or(inArray(memoryRelationships.fromId, ids), inArray(memoryRelationships.toId, ids))).returning({ id: memoryRelationships.id }));
    return { tombstoned, unlinked };
  }

  /**
   * Tombstones the source in one statement and returns how many chunks it removed.
   * The statement is an UPDATE builder so a drizzle cache sees the mutation of
   * `memories` (a SELECT over data-modifying CTEs would be cached as a read).
   * Its relationship CTE selects the same live chunks the UPDATE changes: the
   * advisory and row locks held by withSourceLock keep that set fixed.
   */
  private async clearSource(tx: PostgresJsDatabase<any>, scope: SourceScope, tags: string[], now: Date): Promise<number> {
    const live = tx.select({ id: memories.id }).from(memories).where(this.liveSource(scope, tags));
    const unlinked = tx.$with('source_unlinked').as(tx.delete(memoryRelationships)
      .where(or(inArray(memoryRelationships.fromId, live), inArray(memoryRelationships.toId, live))).returning({ id: memoryRelationships.id }));
    const rows = await tx.with(unlinked).update(memories).set(this.tombstone(now))
      .where(this.liveSource(scope, tags)).returning({ id: memories.id });
    return rows.length;
  }

  async getSourceState(input: SourceScope): Promise<SourceState | null> {
    const { scope, tags } = requireSourceScope(input);
    const rows = await this.db.select({ contentHash: memories.contentHash, chunkCount: sql<number>`count(*)::int` })
      .from(memories).where(this.liveSource(scope, tags)).groupBy(memories.contentHash);
    if (!rows.length) return null;
    return {
      contentHash: rows.length === 1 ? rows[0].contentHash : null,
      chunkCount: rows.reduce((total, row) => total + Number(row.chunkCount), 0),
    };
  }

  async replaceSource(input: SourceReplace): Promise<Memory[]> {
    const { scope, tags, contentHash, chunks } = requireSourceReplace(input);
    const now = new Date();
    const values = chunks.map((chunk, chunkIndex) => ({
      ...this.toRow(chunk, now), sourceKey: scope.sourceKey, contentHash, chunkIndex,
    }));
    return this.withSourceLock(scope, tags, async tx => {
      if (!values.length) { await this.clearSource(tx, scope, tags, now); return []; }
      const { tombstoned, unlinked } = this.tombstoneSource(tx, scope, tags, now);
      const rows = await tx.with(tombstoned, unlinked).insert(memories).values(values).returning();
      return rows.map(row => this.mapToDomain(row));
    });
  }

  async deleteSource(input: SourceScope): Promise<number> {
    const { scope, tags } = requireSourceScope(input);
    return this.withSourceLock(scope, tags, tx => this.clearSource(tx, scope, tags, new Date()));
  }

  private mapToDomain(row: typeof memories.$inferSelect): Memory {
    return {
      id: row.id,
      tenantId: row.tenantId,
      containerTags: row.containerTags,
      type: row.type as any,
      content: row.content,
      embedding: row.embedding,
      metadata: row.metadata as Record<string, any>,
      isLatest: row.isLatest,
      revision: row.revision,
      deletedAt: row.deletedAt?.getTime() ?? null,
      createdAt: row.createdAt.getTime(),
      updatedAt: row.updatedAt.getTime(),
      ...(row.sourceKey == null ? {} : {
        sourceKey: row.sourceKey,
        ...(row.contentHash == null ? {} : { contentHash: row.contentHash }),
        ...(row.chunkIndex == null ? {} : { chunkIndex: row.chunkIndex }),
      }),
    };
  }
}
