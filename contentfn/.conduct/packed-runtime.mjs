import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { createRequire } from 'node:module';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createContentfnServer } from '@contentfn/server';
import { createContentfnClient } from '@contentfn/client';
import { memoryAdapter } from '@superfunctions/db/adapters/memory';
const require = createRequire(import.meta.url);
assert.equal(typeof require('@contentfn/server').createContentfnServer, 'function');
assert.equal(typeof require('@contentfn/client').createContentfnClient, 'function');
assert.equal(typeof require('@contentfn/core').validateSchema, 'function');
const db = memoryAdapter(); const content = createContentfnServer({ db });
const http = createServer(content.handler); await new Promise(resolve => http.listen(0, '127.0.0.1', resolve));
try {
 const baseUrl = `http://127.0.0.1:${http.address().port}`;
 const client = createContentfnClient({ baseUrl });
 assert.equal((await client.datasets.create({dataset:'packed'})).ok,true);
 assert.equal((await client.schema.upsert({dataset:'packed', schema:{version:1,documentTypes:[{name:'post',fields:[]}]}})).ok,true);
 assert.equal((await client.docs.create({dataset:'packed',id:'one',type:'post',doc:{},asDraft:true})).ok,true);
 assert.equal((await client.docs.publish({dataset:'packed',id:'one'})).ok,true);
 assert.equal((await client.docs.get({dataset:'packed',id:'one'})).result._id,'one');
 const queries = client.realtime.subscribe({dataset:'packed',query:{dataset:'packed'}});
 const snapshot = await queries.next();
 assert.equal(snapshot.value.result.eventType,'query.snapshot');
 assert.equal(snapshot.value.result.queryResult.data.length,1);
 await queries.return();
 assert.equal(require('@contentfn/server').getSchema().version,3);
 assert.equal(require('@contentfn/server').getSchema().schemas.length,13);
 const audit = await client.audit.query({dataset:'packed',action:'docs.create'});
 assert.equal(audit.ok,true);
 assert.equal(audit.result.records.length,1);
 assert.deepEqual(audit.result.records[0].targetIds,['packed','drafts.one']);
 const exported = await client.datasets.export({dataset:'packed'});
 assert.equal(exported.result.dataset,'packed'); assert.equal(typeof exported.result.exportedAt,'string');
 const cli = await promisify(execFile)(process.execPath,['node_modules/@contentfn/cli/dist/index.js','--server',baseUrl,'doc','get','--dataset','packed','--id','one']);
 assert.match(cli.stdout, /one/);
 console.log(`Packed ESM/CJS/HTTP/CLI passed on ${process.version}`);
} finally { await new Promise(resolve=>http.close(resolve)); await db.close(); }
